//! Graduation step 3/3: lock all LP tokens in Raydium Burn & Earn.
//!
//! The liquidity becomes permanently non-withdrawable; the lock program mints
//! a fee-key NFT to the program's fee-key vault PDA so post-graduation pool
//! fees remain claimable by the protocol. Whatever is left of the migration
//! reserve then goes to the treasury.

use anchor_lang::prelude::*;
use anchor_lang::solana_program::program::invoke_signed;
use anchor_lang::system_program;
use anchor_spl::associated_token::AssociatedToken;
use anchor_spl::token::Token;
use anchor_spl::token_interface::{Mint, TokenAccount};

use crate::constants::*;
use crate::error::ParabullError;
use crate::events::LiquidityLocked;
use crate::raydium::{cpmm_accounts, lock_accounts, sort_pool_mints, LockCpLiquidity, METADATA_PROGRAM_ID, WSOL_MINT};
use crate::state::{BondingCurve, Global, MigrationStage};

#[derive(Accounts)]
pub struct LockMigratedLp<'info> {
    #[account(mut, address = global.crank_authority @ ParabullError::Unauthorized)]
    pub crank: Signer<'info>,

    #[account(seeds = [SEED_GLOBAL], bump = global.bump)]
    pub global: Box<Account<'info, Global>>,

    pub mint: Box<InterfaceAccount<'info, Mint>>,

    #[account(mut, seeds = [SEED_BONDING_CURVE, mint.key().as_ref()], bump = bonding_curve.bump)]
    pub bonding_curve: Box<Account<'info, BondingCurve>>,

    /// LP owner and rent payer for the lock accounts (from the reserve).
    #[account(mut, seeds = [SEED_MIGRATION_AUTHORITY, mint.key().as_ref()], bump)]
    pub migration_authority: SystemAccount<'info>,

    /// CHECK: data-less PDA that owns every fee-key NFT.
    #[account(seeds = [SEED_FEE_KEY_VAULT], bump)]
    pub fee_key_vault: UncheckedAccount<'info>,

    /// Fresh keypair generated by the crank; the lock program initialises it.
    #[account(mut)]
    pub fee_nft_mint: Signer<'info>,

    #[account(mut, address = global.treasury @ ParabullError::InvalidAuthority)]
    pub treasury: SystemAccount<'info>,

    /// CHECK: configured Burn & Earn program.
    #[account(address = global.lp_lock_program @ ParabullError::InvalidMigrationAccount, executable)]
    pub lp_lock_program: UncheckedAccount<'info>,
    /// CHECK: configured Burn & Earn authority.
    #[account(address = global.lp_lock_authority @ ParabullError::InvalidMigrationAccount)]
    pub lp_lock_authority: UncheckedAccount<'info>,

    /// CHECK: must be the pool recorded by `migrate_raydium`.
    #[account(address = bonding_curve.raydium_pool @ ParabullError::InvalidMigrationAccount)]
    pub pool_state: UncheckedAccount<'info>,
    /// CHECK: derived and compared in the handler.
    pub lp_mint: UncheckedAccount<'info>,
    #[account(
        mut,
        token::mint = lp_mint,
        token::authority = migration_authority,
        token::token_program = token_program,
    )]
    pub creator_lp_token: Box<InterfaceAccount<'info, TokenAccount>>,
    /// CHECK: derived and compared in the handler.
    #[account(mut)]
    pub token_0_vault: UncheckedAccount<'info>,
    /// CHECK: derived and compared in the handler.
    #[account(mut)]
    pub token_1_vault: UncheckedAccount<'info>,
    /// CHECK: derived and compared in the handler.
    #[account(mut)]
    pub fee_nft_account: UncheckedAccount<'info>,
    /// CHECK: derived and compared in the handler.
    #[account(mut)]
    pub locked_liquidity: UncheckedAccount<'info>,
    /// CHECK: derived and compared in the handler.
    #[account(mut)]
    pub lock_lp_vault: UncheckedAccount<'info>,
    /// CHECK: derived and compared in the handler.
    #[account(mut)]
    pub nft_metadata: UncheckedAccount<'info>,

    pub rent: Sysvar<'info, Rent>,
    pub system_program: Program<'info, System>,
    pub token_program: Program<'info, Token>,
    pub associated_token_program: Program<'info, AssociatedToken>,
    /// CHECK: Metaplex token metadata program.
    #[account(address = METADATA_PROGRAM_ID)]
    pub metadata_program: UncheckedAccount<'info>,
}

pub fn handler(ctx: Context<LockMigratedLp>) -> Result<()> {
    let bump = [ctx.bumps.migration_authority];
    let a = &ctx.accounts;
    require!(a.bonding_curve.stage() == MigrationStage::PoolCreated, ParabullError::InvalidMigrationStage);

    let mint_key = a.mint.key();
    let creator = a.migration_authority.key();
    let order = sort_pool_mints(&mint_key, &WSOL_MINT)?;
    let pool = cpmm_accounts(&a.global.cpmm_program, &a.global.cpmm_amm_config, &order, &creator);
    let lock = lock_accounts(&a.lp_lock_program.key(), &a.lp_lock_authority.key(), &a.fee_nft_mint.key(), &a.fee_key_vault.key(), &pool.lp_mint);
    for (passed, expected) in [
        (a.pool_state.key(), pool.pool_state),
        (a.lp_mint.key(), pool.lp_mint),
        (a.creator_lp_token.key(), pool.creator_lp_token),
        (a.token_0_vault.key(), pool.token_0_vault),
        (a.token_1_vault.key(), pool.token_1_vault),
        (a.fee_nft_account.key(), lock.fee_nft_account),
        (a.locked_liquidity.key(), lock.locked_liquidity),
        (a.lock_lp_vault.key(), lock.lock_lp_vault),
        (a.nft_metadata.key(), lock.nft_metadata),
    ] {
        require_keys_eq!(passed, expected, ParabullError::InvalidMigrationAccount);
    }

    let lp_amount = a.creator_lp_token.amount;
    require!(lp_amount > 0, ParabullError::ZeroAmount);
    let signer: &[&[&[u8]]] = &[&[SEED_MIGRATION_AUTHORITY, mint_key.as_ref(), &bump]];

    let ix = LockCpLiquidity {
        program: a.lp_lock_program.key(),
        authority: a.lp_lock_authority.key(),
        payer: creator,
        liquidity_owner: creator,
        fee_nft_owner: a.fee_key_vault.key(),
        fee_nft_mint: a.fee_nft_mint.key(),
        pool_state: pool.pool_state,
        lp_mint: pool.lp_mint,
        liquidity_owner_lp: pool.creator_lp_token,
        token_0_vault: pool.token_0_vault,
        token_1_vault: pool.token_1_vault,
        accounts: lock,
        lp_amount,
        with_metadata: true,
    }
    .instruction();
    invoke_signed(
        &ix,
        &[
            a.lp_lock_authority.to_account_info(),
            a.migration_authority.to_account_info(),
            a.fee_key_vault.to_account_info(),
            a.fee_nft_mint.to_account_info(),
            a.fee_nft_account.to_account_info(),
            a.pool_state.to_account_info(),
            a.locked_liquidity.to_account_info(),
            a.lp_mint.to_account_info(),
            a.creator_lp_token.to_account_info(),
            a.lock_lp_vault.to_account_info(),
            a.token_0_vault.to_account_info(),
            a.token_1_vault.to_account_info(),
            a.nft_metadata.to_account_info(),
            a.rent.to_account_info(),
            a.system_program.to_account_info(),
            a.token_program.to_account_info(),
            a.associated_token_program.to_account_info(),
            a.metadata_program.to_account_info(),
            a.lp_lock_program.to_account_info(),
        ],
        signer,
    )?;

    // Unspent reserve -> treasury (system transfer signed by the PDA).
    let leftover = a.migration_authority.lamports();
    if leftover > 0 {
        system_program::transfer(
            CpiContext::new_with_signer(
                a.system_program.to_account_info(),
                system_program::Transfer { from: a.migration_authority.to_account_info(), to: a.treasury.to_account_info() },
                signer,
            ),
            leftover,
        )?;
    }

    let fee_nft_mint = a.fee_nft_mint.key();
    let fee_key_vault = a.fee_key_vault.key();
    let c = &mut ctx.accounts.bonding_curve;
    c.migration_stage = MigrationStage::LpLocked as u8;
    c.fee_nft_mint = fee_nft_mint;

    emit!(LiquidityLocked {
        mint: mint_key,
        pool: pool.pool_state,
        lp_amount,
        fee_nft_mint,
        fee_nft_owner: fee_key_vault,
        reserve_refunded_to_treasury: leftover,
    });
    Ok(())
}
